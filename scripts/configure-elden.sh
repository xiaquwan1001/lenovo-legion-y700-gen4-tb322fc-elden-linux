#!/bin/bash
# Generate .config for the Lenovo TB322FC (SM8750, "elden") bring-up kernel.
#
# Adapted from xiaobai-Lethe/Y700-elden-linux project/configure-elden.sh
# (which targets a tree using the older NT36523 panel driver) to the
# GEEKiDoS/linux v7.2-elden tree, whose elden DT binds:
#     display: "csot,pp8807hb1-1", "novatek,nt36536"
#     touch:   "novatek,nt36536-ts"   -> TOUCHSCREEN_NOVATEK_NVT36XXX_SPI
#
# Everything that must be reachable from the RAM initramfs is built in ("no
# modules in the ramdisk"). Symbol names are checked against this tree; any
# unknown ones are reported and harmless (olddefconfig drops them).
set -e
ROOT=${ROOT:-$HOME/y700-elden}
cd "$ROOT/linux"
export ARCH=arm64 CROSS_COMPILE=aarch64-linux-gnu-

make defconfig

C=scripts/config

# --- SoC / pinctrl / clocks ---
$C -e ARCH_QCOM
$C -e PINCTRL_SM8750
$C -e SM_GCC_8750 -e SM_TCSRCC_8750 -e SM_DISPCC_8750 -e SM_GPUCC_8750 -e SM_VIDEOCC_8750
$C -e INTERCONNECT_QCOM_SM8750
$C -e QCOM_RPMH -e QCOM_RPMHPD -e QCOM_COMMAND_DB -e QCOM_SMEM -e QCOM_PDC
$C -e QCOM_SCM -e QCOM_TCSR -e QCOM_LLCC -e QCOM_SOCINFO
$C -e REGULATOR_QCOM_RPMH -e REGULATOR_QCOM_SPMI -e REGULATOR_FIXED_VOLTAGE
$C -e SPMI -e SPMI_MSM_PMIC_ARB -e MFD_SPMI_PMIC -e PINCTRL_QCOM_SPMI_PMIC
$C -e INPUT_PM8941_PWRKEY -e KEYBOARD_GPIO
$C -e POWER_RESET_QCOM_PON -e RTC_DRV_PM8XXX
$C -e QCOM_SPMI_ADC5 -e QCOM_SPMI_ADC5_GEN3 -e QCOM_VADC_COMMON
$C -e NVMEM_SPMI_SDAM -e NVMEM_REBOOT_MODE -e REBOOT_MODE
$C -e ARM_SMMU -e ARM_SMMU_QCOM
$C -e SERIAL_QCOM_GENI -e SERIAL_QCOM_GENI_CONSOLE -e QCOM_GENI_SE
$C -e I2C_QCOM_GENI -e SPI_QCOM_GENI -e I2C_CHARDEV
$C -e QCOM_CLK_RPMH -e COMMON_CLK_QCOM

# --- UFS (real root filesystem lives here eventually) ---
$C -e SCSI -e BLK_DEV_SD -e SCSI_UFSHCD -e SCSI_UFSHCD_PLATFORM -e SCSI_UFS_QCOM
$C -e PHY_QCOM_QMP -e PHY_QCOM_QMP_UFS
$C -e EXT4_FS -e F2FS_FS -e BTRFS_FS -e VFAT_FS -e NLS_CODEPAGE_437 -e NLS_ISO8859_1

# --- USB device mode: console/network path during bring-up ---
$C -e USB -e USB_XHCI_HCD -e USB_DWC3 -e USB_DWC3_QCOM -e USB_DWC3_DUAL_ROLE
$C -e PHY_QCOM_M31_EUSB -e PHY_QCOM_EUSB2_REPEATER -e PHY_QCOM_QMP_COMBO -e PHY_QCOM_QMP_USB
$C -e USB_ROLE_SWITCH -e TYPEC -e TYPEC_UCSI -e UCSI_PMIC_GLINK -e QCOM_PMIC_GLINK
$C -e USB_GADGET -e USB_CONFIGFS -e USB_CONFIGFS_SERIAL -e USB_CONFIGFS_ACM
$C -e USB_CONFIGFS_NCM -e USB_CONFIGFS_ECM -e USB_CONFIGFS_RNDIS -e USB_CONFIGFS_MASS_STORAGE
$C -e USB_CONFIGFS_F_FS -e USB_LIBCOMPOSITE -e USB_F_ACM -e USB_F_SERIAL -e USB_F_NCM -e USB_F_RNDIS
$C -d USB_G_SERIAL -d USB_ETH
$C -e U_SERIAL_CONSOLE
$C -e CONFIGFS_FS

# --- Display: firmware framebuffer via simple-framebuffer + fbcon ---
$C -e DRM -e DRM_SIMPLEDRM -e DRM_FBDEV_EMULATION
$C -e FB -e FRAMEBUFFER_CONSOLE -e FRAMEBUFFER_CONSOLE_DETECT_PRIMARY
$C -e FRAMEBUFFER_CONSOLE_ROTATION -e LOGO -e FONTS -e FONT_TER16x32
$C -e VT -e VT_CONSOLE

# --- Real display pipeline: MDSS/DPU + DSI + NT36536 panel ---
# DRM_MSM is a tristate that silently caps itself at "m" unless QCOM_OCMEM is
# deliberately off, the SND_SOC stack is on, and BACKLIGHT_CLASS_DEVICE exists.
$C -d QCOM_OCMEM
$C -e SOUND -e SND -e SND_TIMER -e SND_PCM -e SND_SOC
$C -e BACKLIGHT_CLASS_DEVICE
$C -e DRM_MSM -e DRM_MSM_KMS -e DRM_MSM_DPU -e DRM_MSM_DSI -e DRM_MSM_DSI_7NM_PHY
$C -e DRM_PANEL_NOVATEK_NT36536

# --- Debugging helpers ---
$C -e PSTORE -e PSTORE_RAM -e PSTORE_CONSOLE -e PSTORE_PMSG
$C -e MAGIC_SYSRQ -e PANIC_TIMEOUT --set-val PANIC_TIMEOUT 10
$C -e DEBUG_INFO_NONE
$C -d DEBUG_INFO_DWARF_TOOLCHAIN_DEFAULT
$C -e IKCONFIG -e IKCONFIG_PROC
$C -e PRINTK_TIME -e PRINTK_CALLER
$C -e DYNAMIC_DEBUG
$C --set-val LOG_BUF_SHIFT 20
$C -e SOFTLOCKUP_DETECTOR -e WQ_WATCHDOG -e PANIC_ON_OOPS
$C -e EROFS_FS -e EXFAT_FS -e NLS_UTF8 -e UNICODE

# --- Initramfs / early userspace ---
$C -e BLK_DEV_INITRD -e RD_GZIP -e RD_XZ -e RD_LZ4 -e RD_ZSTD
$C -e DEVTMPFS -e DEVTMPFS_MOUNT -e TMPFS -e TMPFS_POSIX_ACL
$C -e BINFMT_SCRIPT
$C -e CMDLINE_FROM_BOOTLOADER
$C --set-str CMDLINE "console=ttyGS0 console=tty0 loglevel=7 ignore_loglevel"

# --- Remoteproc / firmware loading ---
$C -e REMOTEPROC -e QCOM_Q6V5_PAS -e QCOM_RPROC_COMMON -e QCOM_SYSMON
$C -e RPMSG_QCOM_GLINK_SMEM -e RPMSG_CHAR -e QCOM_APR
$C -e QCOM_PIL_INFO -e QCOM_MDT_LOADER

# --- CPU DVFS (SCMI over the CPUCP mailbox) ---
$C -e QCOM_CPUCP_MBOX
$C -e ARM_SCMI_CPUFREQ -e ARM_SCMI_PERF_DOMAIN -e ARM_SCMI_POWER_DOMAIN

# --- built-ins that defconfig leaves modular ---
$C -e SERIAL_DEV_BUS -e SERIAL_DEV_CTRL_TTYPORT
$C -e RFKILL
$C -e BT -e BT_QCA -e BT_HCIUART -e BT_HCIUART_SERDEV -e BT_HCIUART_QCA
$C -e BT_HIDP -e UHID -e HIDRAW -e INPUT_MOUSEDEV -e INPUT_EVDEV -e INPUT_JOYDEV
$C -e SND_SOC_QCOM -e SND_SOC_QDSP6
$C -e INPUT_TOUCHSCREEN
$C -e TOUCHSCREEN_NOVATEK_NVT36XXX_SPI
$C -e QRTR -e QRTR_SMD -e QRTR_TUN
$C -e BATTERY_QCOM_BATTMGR -e TYPEC_DP_ALTMODE
$C -e QCOM_PD_MAPPER
$C -e QCOM_SPMI_TEMP_ALARM -e QCOM_SPMI_ADC_TM5 -e QCOM_WDT -e QCOM_STATS
$C -e QCOM_GPI_DMA
$C -e INPUT_FF_MEMLESS -e INPUT_AW86927
$C -e POWER_SEQUENCING -e POWER_SEQUENCING_QCOM_WCN
$C -e PCI -e PCIE_QCOM -e PHY_QCOM_QMP_PCIE
$C -e CFG80211 -e MAC80211 -e MHI_BUS -e QRTR_MHI -e ATH12K -e ATH12K_DEBUG -e ATH12K_DEBUGFS
$C -e ATH12K_COREDUMP -e DEV_COREDUMP -e WANT_DEV_COREDUMP
$C -e FW_LOADER_COMPRESS -e FW_LOADER_COMPRESS_ZSTD -e FW_LOADER_COMPRESS_XZ

# --- Audio: AudioReach on ADSP + LPASS macros + WCD9395 ---
$C -e SOUNDWIRE -e SOUNDWIRE_QCOM -e REGMAP_SOUNDWIRE
$C -e SND_SOC_QCOM_COMMON -e SND_SOC_QCOM_SDW -e SND_SOC_SC8280XP
$C -e SND_SOC_LPASS_MACRO_COMMON -e SND_SOC_LPASS_RX_MACRO
$C -e SND_SOC_LPASS_TX_MACRO -e SND_SOC_LPASS_VA_MACRO -e SND_SOC_LPASS_WSA_MACRO
$C -e SND_SOC_WCD_COMMON -e SND_SOC_WCD_CLASSH -e SND_SOC_WCD_MBHC
$C -e SND_SOC_WCD939X -e SND_SOC_WCD939X_SDW
$C -e SND_HWDEP -e SND_RAWMIDI
$C -e PINCTRL_LPASS_LPI -e PINCTRL_SM8650_LPASS_LPI

# --- slim the build: cannot work here ---
$C -d MODULE_SIG -d MODULE_SIG_ALL
$C -d ACPI
$C -d XEN
$C -d KVM

make olddefconfig

# Second pass for options whose deps only became visible after the first pass.
$C -e PHY_QCOM_QMP_UFS -e PHY_QCOM_QMP_COMBO -e PHY_QCOM_QMP_USB
sed -i 's/^# CONFIG_FONT_TER16x32 is not set/CONFIG_FONT_TER16x32=y/' .config
make olddefconfig

echo
echo "==== key options ===="
grep -E '^CONFIG_(ARCH_QCOM|PINCTRL_SM8750|SM_GCC_8750|SCSI_UFS_QCOM|USB_DWC3_QCOM|USB_CONFIGFS_NCM|DRM_SIMPLEDRM|DRM_MSM|DRM_PANEL_NOVATEK_NT36536|TOUCHSCREEN_NOVATEK_NVT36XXX_SPI|FRAMEBUFFER_CONSOLE|CMDLINE|PHY_QCOM_EUSB2_REPEATER|INTERCONNECT_QCOM_SM8750)=' .config
