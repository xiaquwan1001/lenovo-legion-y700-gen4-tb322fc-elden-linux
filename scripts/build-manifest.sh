#!/bin/bash
# build-manifest.sh — record everything needed to identify/rebuild a boot image.
#
# usage: scripts/build-manifest.sh <version> [image]
#   writes out/boot-elden-<version>.manifest (key=value, machine-readable).
#
# This closes the "vk49 build command was lost" gap: the manifest stores the
# kernel/DTB/.config/ramdisk/image hashes, the exact cmdline and mkbootimg argv,
# and both git HEADs.  Commit the manifests (they are tiny, text-only).
set -euo pipefail
ROOT=${ROOT:-$(cd "$(dirname "$0")/.." && pwd)}
KDIR=$ROOT/linux
OUT=$ROOT/out
VERSION=${1:?usage: build-manifest.sh <version> [image]}
IMG=${2:-$OUT/boot-elden-$VERSION.img}
MANIFEST=$OUT/boot-elden-$VERSION.manifest

sha() { [ -e "$1" ] && sha256sum "$1" | cut -d' ' -f1 || echo "(absent)"; }

# Kernel release as the tree would report it (best effort; no build triggered).
KV=$(make -s -C "$KDIR" ARCH=arm64 CROSS_COMPILE="${CROSS_COMPILE:-aarch64-linux-gnu-}" \
	kernelrelease 2>/dev/null || echo "(unknown)")

KHEAD=$(git -C "$KDIR" rev-parse HEAD 2>/dev/null || echo "(none)")
KDIRTY=$(git -C "$KDIR" status --porcelain 2>/dev/null | head -1 || true)
[ -n "$KDIRTY" ] && KDIRTY="dirty" || KDIRTY="clean"
PHEAD=$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo "(none)")

{
	echo "# boot image manifest — generated by scripts/build-manifest.sh"
	echo "version=$VERSION"
	echo "generated=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
	echo "image=$IMG"
	echo "image_sha256=$(sha "$IMG")"
	echo "image_size=$( [ -e "$IMG" ] && stat -c%s "$IMG" || echo 0 )"
	echo "kernel_release=$KV"
	echo "kernel=$KDIR/arch/arm64/boot/Image.gz"
	echo "kernel_sha256=$(sha "$KDIR/arch/arm64/boot/Image.gz")"
	echo "kernel_image_sha256=$(sha "$KDIR/arch/arm64/boot/Image")"
	echo "dtb=$KDIR/arch/arm64/boot/dts/qcom/sm8750-lenovo-elden.dtb"
	echo "dtb_sha256=$(sha "$KDIR/arch/arm64/boot/dts/qcom/sm8750-lenovo-elden.dtb")"
	echo "config_sha256=$(sha "$KDIR/.config")"
	echo "ramdisk=${RAMDISK_FILE:-(unknown)}"
	echo "ramdisk_sha256=$(sha "${RAMDISK_FILE:-/nonexistent}")"
	echo "cmdline=${CMDLINE:-(unknown)}"
	echo "mkbootimg_args=${MKBOOTIMG_ARGS:-(unknown)}"
	echo "kernel_git_head=$KHEAD"
	echo "kernel_git_state=$KDIRTY"
	echo "project_git_head=$PHEAD"
} > "$MANIFEST"

echo "[manifest] $MANIFEST"
grep -E '^(version|kernel_release|image_sha256|ramdisk|cmdline)=' "$MANIFEST"
